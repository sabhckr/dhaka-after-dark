export const PROFILE_LIST: Profile[] = ROLE_IDS.map((id) => PROFILES[id]);

export function profileIssues(profile: Profile): string[] {
  const issues: string[] = [];
  if (!profile.name) issues.push("name");
  if (!profile.meshId) issues.push("mesh");
  if (!(profile.speed > 0.4 && profile.speed <= 9)) issues.push("speed");
  if (profile.run < profile.speed || profile.run > 10) issues.push("run");
  if (!(profile.turn > 0.4 && profile.turn < 8)) issues.push("turn");
  if (!(profile.radius >= 0.25 && profile.radius <= 0.8)) issues.push("radius");
  if (!profile.capabilities.length) issues.push("capabilities");
  if (!profile.implemented.length || !profile.missing.length) issues.push("status");
  if (!(profile.perception >= 8 && profile.perception <= 40)) issues.push("perception");
  if (!(profile.reaction >= 0.15 && profile.reaction <= 2)) issues.push("reaction");
  if (!(profile.risk >= 0 && profile.risk <= 1)) issues.push("risk");
  for (const part of ["early", "day", "evening", "late"] as const) {
    if (!profile.schedule[part]) issues.push(`schedule ${part}`);
    if (!(profile.density[part] >= 0)) issues.push(`density ${part}`);
  }
  if (profile.capabilities.includes("police") && profile.radio < 80) issues.push("radio");
  if (!profile.capabilities.includes("police") && profile.radio !== 0) issues.push("radio");
  return issues;
}
